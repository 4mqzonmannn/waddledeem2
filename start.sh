#!/bin/bash
# このスクリプトは、仮想環境を有効化し、Discordボットを起動します。
# ボットが停止した場合は、自動的に再起動します。

# このスクリプトが存在するディレクトリに移動する
cd "$(dirname "$0")"

# 仮想環境 (venv) を有効化 (ループ外で一度だけ)
source ./venv/bin/activate

# 無限ループでボットを監視・実行
while true
do
    echo "-----------------------------------"
    echo "ボットを起動します... (`date`)"
    echo "-----------------------------------"
    
    # Pythonスクリプトを実行 (バックグラウンドではなく、フォアグラウンドで実行)
    python3 ./wad.py
    
    # 上のpython3コマンドが終了した場合のみ、以下の処理が実行される
    echo "-----------------------------------"
    echo "ボットが停止しました。5秒後に再起動します。"
    echo "スクリプトを完全に終了するには Control + C を押してください。"
    echo "-----------------------------------"
    sleep 5 # 5秒間待機
done

